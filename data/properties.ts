/** Fills in price per sq.ft for sale listings measured in sq.ft or sq.yd. */
function finalise(d: Draft): Property {
  if (d.pricePerSqft !== undefined || d.listingType !== "sale" || d.area.unit === "acre") return d as Property;
  return { ...d, pricePerSqft: Math.round(d.price / areaInSqft(d.area)) };
}

export const properties: Property[] = drafts.map(finalise);

export function getProperty(slug: string) {
  return properties.find((p) => p.slug === slug);
}

export function getSimilar(p: Property, limit = 3) {
  const sameCity = properties.filter((x) => x.id !== p.id && x.category === p.category && x.city === p.city);
  const sameCat = properties.filter((x) => x.id !== p.id && x.category === p.category && x.city !== p.city);
  return [...sameCity, ...sameCat].slice(0, limit);
}

/** Price per acre for farmland, used in cards and specs. */
export function pricePerAcre(p: Property) {
  return p.area.unit === "acre" && p.listingType === "sale" ? Math.round(p.price / p.area.value) : undefined;
}
